def set_paragraph_rtl(paragraph):
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_pr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    bidi.set(qn('w:val'), '1')
    p_pr.append(bidi)


def add_ar_heading(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    set_paragraph_rtl(p)
    for r in p.runs:
        r.font.name = 'Arial'
        r.font.size = Pt(18 if level == 1 else 15)


def add_ar_paragraph(doc, text, size=13, bold=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = 'Arial'
    run.font.size = Pt(size)
    run.bold = bold
    set_paragraph_rtl(p)
    return p


def create_diagram(path: Path, title: str, nodes: list[str], arrows: list[tuple[int, int]]):
    w, h = 1600, 1000
    img = Image.new('RGB', (w, h), 'white')
    d = ImageDraw.Draw(img)
    try:
        font_title = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 50)
        font_node = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 30)
    except Exception:
        font_title = ImageFont.load_default()
        font_node = ImageFont.load_default()

    d.text((w//2 - 280, 35), title, fill='black', font=font_title)
    positions = [
        (180, 220), (640, 220), (1100, 220),
        (180, 600), (640, 600), (1100, 600),
    ]
    boxes = []
    for i, node in enumerate(nodes[:6]):
        x, y = positions[i]
        box = (x, y, x + 320, y + 160)
        boxes.append(box)
        d.rounded_rectangle(box, radius=18, outline='navy', width=4, fill='#EEF3FF')
        d.multiline_text((x + 16, y + 52), node, fill='black', font=font_node, spacing=6)

    for a, b in arrows:
        if a < len(boxes) and b < len(boxes):
            ax = (boxes[a][0] + boxes[a][2]) // 2
            ay = (boxes[a][1] + boxes[a][3]) // 2
            bx = (boxes[b][0] + boxes[b][2]) // 2
            by = (boxes[b][1] + boxes[b][3]) // 2
            d.line((ax, ay, bx, by), fill='darkred', width=5)
            d.polygon([(bx, by), (bx - 12, by - 8), (bx - 12, by + 8)], fill='darkred')

    img.save(path)


